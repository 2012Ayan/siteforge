# SECTION TITLE
# ============================================================

def section_title(title, styles):

    return Paragraph(
        escape(title),
        styles["Section"]
    )


# ============================================================
# SCORE
# ============================================================

def get_score(scores, key):

    if not isinstance(scores, dict):
        return 0

    value = scores.get(
        key,
        0
    )

    try:
        return int(value)
    except:
        return 0


# ============================================================
# ASSESSMENT
# ============================================================

def assessment(score):

    if score >= 90:
        return "Excellent"

    if score >= 80:
        return "Good"

    if score >= 70:
        return "Needs Improvement"

    if score >= 50:
        return "Weak"

    return "Critical"


# ============================================================
# HEALTH
# ============================================================

def get_health(score):

    if score >= 90:
        return "Excellent"

    if score >= 80:
        return "Good"

    if score >= 70:
        return "Needs Improvement"

    if score >= 50:
        return "Weak"

    return "Critical"


# ============================================================
# YES / NO
# ============================================================

def yes_no(value):

    return "Detected" if value else "Not Detected"


# ============================================================
# TABLE
# ============================================================

def make_table(rows, widths):

    table = Table(
        rows,
        colWidths=widths,
        repeatRows=1
    )

    table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.HexColor("#111827")
            ),

            (
                "TEXTCOLOR",
                (0, 0),
                (-1, 0),
                colors.white
            ),

            (
                "FONTNAME",
                (0, 0),
                (-1, 0),
                "Helvetica-Bold"
            ),

            (
                "FONTSIZE",
                (0, 0),
                (-1, -1),
                8.5
            ),

            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.35,
                colors.HexColor("#D1D5DB")
            ),

            (
                "ROWBACKGROUNDS",
                (0, 1),
                (-1, -1),
                [
                    colors.white,
                    colors.HexColor("#F9FAFB")
                ]
            ),

            (
                "VALIGN",
                (0, 0),
                (-1, -1),
                "MIDDLE"
            ),

            (
                "LEFTPADDING",
                (0, 0),
                (-1, -1),
                7
            ),

            (
                "RIGHTPADDING",
                (0, 0),
                (-1, -1),
                7
            ),

            (
                "TOPPADDING",
                (0, 0),
                (-1, -1),
                6
            ),

            (
                "BOTTOMPADDING",
                (0, 0),
                (-1, -1),
                6
            )
        ])
    )

    return table


# ============================================================
# FOOTER
# ============================================================

def add_footer(canvas, doc):

    canvas.saveState()

    canvas.setFont(
        "Helvetica",
        7
    )

    canvas.setFillColor(
        colors.HexColor("#9CA3AF")
    )

    canvas.drawString(
        18 * mm,
        10 * mm,
        "Generated by SiteForge AI"
    )

    canvas.drawRightString(
        A4[0] - 18 * mm,
        10 * mm,
        f"Page {doc.page}"
    )

    canvas.restoreState()


# ============================================================
# HTML ESCAPE
# ============================================================

def escape(value):

    value = str(value)

    return (
        value
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&#39;")
    )